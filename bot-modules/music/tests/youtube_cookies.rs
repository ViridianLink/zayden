/// yt-dlp downgrades a dead session to a *warning* and carries on
/// unauthenticated, so the symptom is the original 403s returning with no
/// explanation. This is what turns that back into a diagnosable event.
#[test]
fn a_rotated_session_is_picked_out_of_yt_dlp_stderr() {
    let stderr = "\
[youtube] Extracting URL: https://www.youtube.com/watch?v=abc\n\
WARNING: The provided YouTube account cookies are no longer valid. They have \
likely been rotated in the browser as a security measure.\n\
[youtube] abc: Downloading webpage\n";

    let warning = cookie_warning(stderr).expect("the rotation warning is found");

    assert!(warning.contains("no longer valid"));
}

#[test]
fn ordinary_stderr_chatter_is_not_reported_as_a_cookie_problem() {
    let stderr = "\
[youtube] Extracting URL: https://www.youtube.com/watch?v=abc\n\
[youtube] abc: Downloading tv client config\n\
WARNING: Falling back to generic n function search\n";

    assert_eq!(cookie_warning(stderr), None);
}
