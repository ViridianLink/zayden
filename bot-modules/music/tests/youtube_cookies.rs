//! Cookie-jar authentication for the `yt-dlp` child processes.
//!
//! A datacenter IP with no session eventually gets 403s from every player
//! client, so `--cookies` is the remedy. These tests pin the three ways that
//! remedy can quietly stop working:
//!
//! * a jar that parses but is read as anonymous (the `#HttpOnly_` trap),
//! * leases that collide or leak the credential into a shared temp directory,
//! * a stream-client list yt-dlp discards the moment it sees cookies.

use std::collections::HashSet;
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicU64, Ordering};

use music::{
    AUTHED_STREAM_CLIENTS,
    COOKIE_UNSUPPORTED_CLIENTS,
    CookieJar,
    JarStatus,
    STREAM_CLIENTS,
    cookie_warning,
    has_netscape_header,
    jar_status,
    parse_netscape,
    stream_clients,
};

const HEADER: &str = "# Netscape HTTP Cookie File\n";

/// A jar exported from a signed-in browser: the two `__Secure-*` session IDs
/// arrive `HttpOnly`, i.e. behind a leading `#`.
fn authenticated_jar(expiry: i64) -> String {
    format!(
        "{HEADER}# This file is generated by yt-dlp.  Do not edit.\n\
         \n\
         .youtube.com\tTRUE\t/\tTRUE\t{expiry}\tLOGIN_INFO\tAFmmF2s\n\
         #HttpOnly_.youtube.com\tTRUE\t/\tTRUE\t{later}\t__Secure-3PAPISID\tabc/def\n\
         #HttpOnly_.youtube.com\tTRUE\t/\tTRUE\t{later}\t__Secure-1PAPISID\tabc/def\n\
         .youtube.com\tTRUE\t/\tFALSE\t0\tPREF\ttz=Europe.London\n",
        later = expiry + 1_000,
    )
}

/// Everything a cookie exporter picks up from a *logged-out* visit.
fn anonymous_jar() -> String {
    format!(
        "{HEADER}\
         .youtube.com\tTRUE\t/\tFALSE\t2000000000\tPREF\ttz=Europe.London\n\
         .youtube.com\tTRUE\t/\tTRUE\t2000000000\tSOCS\tCAI\n\
         .youtube.com\tTRUE\t/\tTRUE\t2000000000\tVISITOR_INFO1_LIVE\tnope\n"
    )
}

/// Writes `contents` to a uniquely named file under the system temp directory
/// and returns its path. Cleaned up by [`TempFile`]'s drop.
struct TempFile(PathBuf);

impl TempFile {
    fn new(contents: &str) -> std::io::Result<Self> {
        static NEXT: AtomicU64 = AtomicU64::new(0);

        let path = std::env::temp_dir().join(format!(
            "zayden-cookie-test-{}-{}.txt",
            std::process::id(),
            NEXT.fetch_add(1, Ordering::Relaxed)
        ));
        std::fs::write(&path, contents)?;
        Ok(Self(path))
    }

    fn path(&self) -> &Path {
        &self.0
    }
}

impl Drop for TempFile {
    fn drop(&mut self) {
        let _ = std::fs::remove_file(&self.0);
    }
}

// ---------------------------------------------------------------------------
// Parsing
// ---------------------------------------------------------------------------

/// The trap this whole module exists to avoid. `__Secure-1PAPISID` and
/// `__Secure-3PAPISID` are `HttpOnly`, and exporters mark those lines with a
/// leading `#HttpOnly_`. A parser that drops comment lines *before* checking
/// for that prefix throws away exactly the cookies that prove the jar is signed
/// in — and then reports a perfectly good jar as anonymous.
#[test]
fn http_only_lines_are_cookies_not_comments() {
    let jar = authenticated_jar(2_000_000_000);
    let cookies = parse_netscape(&jar);

    let names: Vec<&str> = cookies.iter().map(|c| c.name).collect();
    assert!(
        names.contains(&"__Secure-3PAPISID"),
        "the HttpOnly session cookie was dropped as a comment: {names:?}",
    );

    let secure = cookies
        .iter()
        .find(|c| c.name == "__Secure-3PAPISID")
        .expect("the HttpOnly cookie is present");
    assert!(secure.http_only);
    assert_eq!(secure.domain, ".youtube.com");
}

#[test]
fn real_comments_and_blank_lines_are_skipped() {
    let jar = authenticated_jar(2_000_000_000);
    let cookies = parse_netscape(&jar);

    assert_eq!(
        cookies.len(),
        4,
        "expected exactly the four cookie lines, got {cookies:?}",
    );
    assert!(cookies.iter().all(|c| !c.name.starts_with('#')));
}

#[test]
fn a_zero_expiry_is_a_session_cookie_not_the_epoch() {
    let jar = authenticated_jar(2_000_000_000);
    let cookies = parse_netscape(&jar);

    let pref = cookies.iter().find(|c| c.name == "PREF").expect("PREF is present");
    assert_eq!(pref.expires, None);
}

#[test]
fn malformed_lines_are_ignored_rather_than_panicking() {
    let contents = format!(
        "{HEADER}not\tenough\tfields\n\
         \n\
         # a comment\n\
         .youtube.com\tTRUE\t/\tTRUE\t2000000000\tLOGIN_INFO\tv\n"
    );

    let cookies = parse_netscape(&contents);
    assert_eq!(cookies.len(), 1);
    assert_eq!(cookies.first().map(|c| c.name), Some("LOGIN_INFO"));
}

