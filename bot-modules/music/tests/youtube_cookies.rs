#[test]
fn open_accepts_a_signed_in_jar() {
    let file = TempFile::new(&authenticated_jar(2_000_000_000))
        .expect("write the test cookie file");

    let jar = CookieJar::open(file.path().to_path_buf()).expect("open the jar");

    assert_eq!(jar.path(), file.path());
    assert!(jar.status().is_authenticated());
}

/// A jar with no session is a configuration mistake, not a fatal one: it opens,
/// so the bot can say so once at startup instead of failing every `/play`.
#[test]
fn open_accepts_an_anonymous_jar_so_the_bot_can_report_it() {
    let file = TempFile::new(&anonymous_jar()).expect("write the test cookie file");

    let jar = CookieJar::open(file.path().to_path_buf()).expect("open the jar");

    assert_eq!(jar.status(), JarStatus::Anonymous);
}

#[test]
fn open_rejects_a_file_that_is_not_a_cookie_jar() {
    let file = TempFile::new("LOGIN_INFO=AFmmF2s; SAPISID=abc\n")
        .expect("write the test cookie file");

    let err = CookieJar::open(file.path().to_path_buf())
        .expect_err("a pasted Cookie header must not be accepted");

    assert!(
        err.to_string().contains("Netscape"),
        "the error must name the format the operator has to produce: {err}",
    );
}

#[test]
fn open_reports_a_missing_file() {
    let missing = std::env::temp_dir().join("zayden-cookie-does-not-exist.txt");

    CookieJar::open(missing).expect_err("a missing jar must not open");
}

// ---------------------------------------------------------------------------
// Leases
// ---------------------------------------------------------------------------

/// yt-dlp rewrites whatever file `--cookies` names, persisting cookies YouTube
/// rotated mid-run. Handing it the configured file directly would let two
/// concurrent resolutions interleave writes into the operator's credential —
/// and would break a read-only mount. Each run gets a copy instead.
#[tokio::test]
async fn a_lease_is_a_copy_that_leaves_the_configured_file_alone() {
    let contents = authenticated_jar(2_000_000_000);
    let file = TempFile::new(&contents).expect("write the test cookie file");
    let jar = CookieJar::open(file.path().to_path_buf()).expect("open the jar");

    let lease = jar.lease().await.expect("take a lease");

    assert_ne!(lease.path(), jar.path(), "the lease must not alias the jar");
    assert_eq!(
        std::fs::read_to_string(lease.path()).expect("read the lease"),
        contents,
        "the lease must carry the same session",
    );
    assert_eq!(lease.arg(), lease.path().to_string_lossy());

    // Stand in for yt-dlp's write-back.
    std::fs::write(lease.path(), "# Netscape HTTP Cookie File\n")
        .expect("overwrite the lease");

    assert_eq!(
        std::fs::read_to_string(jar.path()).expect("read the jar"),
        contents,
        "yt-dlp writing to its copy must not touch the configured file",
    );
}

#[tokio::test]
async fn concurrent_leases_never_share_a_path() {
    let file = TempFile::new(&authenticated_jar(2_000_000_000))
        .expect("write the test cookie file");
    let jar = CookieJar::open(file.path().to_path_buf()).expect("open the jar");

    let mut leases = Vec::new();
    for _ in 0..16 {
        leases.push(jar.lease().await.expect("take a lease"));
    }

    let paths: HashSet<PathBuf> =
        leases.iter().map(|lease| lease.path().to_path_buf()).collect();

    assert_eq!(
        paths.len(),
        leases.len(),
        "two concurrent yt-dlp runs would write over each other",
    );
}

#[tokio::test]
async fn dropping_a_lease_unlinks_the_copied_credential() {
    let file = TempFile::new(&authenticated_jar(2_000_000_000))
        .expect("write the test cookie file");
    let jar = CookieJar::open(file.path().to_path_buf()).expect("open the jar");

    let path = {
        let lease = jar.lease().await.expect("take a lease");
        assert!(lease.path().exists());
        lease.path().to_path_buf()
    };

    assert!(
        !path.exists(),
        "a session cookie copy was left behind in the temp directory",
    );
}

/// The lease sits in a world-writable shared directory, so it is created
/// private rather than chmod-ed afterwards — there is no window in which the
/// session is readable by other users on the host.
#[cfg(unix)]
#[tokio::test]
async fn a_lease_is_only_readable_by_this_user() {
    use std::os::unix::fs::PermissionsExt;

    let file = TempFile::new(&authenticated_jar(2_000_000_000))
        .expect("write the test cookie file");
    let jar = CookieJar::open(file.path().to_path_buf()).expect("open the jar");

    let lease = jar.lease().await.expect("take a lease");
    let mode = std::fs::metadata(lease.path())
        .expect("stat the lease")
        .permissions()
        .mode();

    assert_eq!(
        mode & 0o077,
        0,
        "the copied cookies are readable by other users (mode {:o})",
        mode & 0o777,
    );
}

/// A refreshed export should take effect without a restart, so the lease reads
/// the file each time rather than a snapshot taken at open.
#[tokio::test]
async fn a_lease_picks_up_a_jar_replaced_since_startup() {
    let file = TempFile::new(&authenticated_jar(1_000_000_000))
        .expect("write the test cookie file");
    let jar = CookieJar::open(file.path().to_path_buf()).expect("open the jar");

    let refreshed = authenticated_jar(2_000_000_000);
    std::fs::write(file.path(), &refreshed).expect("re-export the jar");

    let lease = jar.lease().await.expect("take a lease");

    assert_eq!(
        std::fs::read_to_string(lease.path()).expect("read the lease"),
        refreshed,
    );
}

