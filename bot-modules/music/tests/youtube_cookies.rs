#[test]
fn accepts_the_header_variants_exporters_actually_emit() {
    assert!(has_netscape_header("# Netscape HTTP Cookie File\n.youtube.com\t"));
    assert!(has_netscape_header("# HTTP Cookie File\n"));
    assert!(has_netscape_header("\n\n#  netscape http cookie file  \n"));
}

/// The single most common operator mistake: pasting a `Cookie:` request header
/// out of devtools instead of exporting a cookies.txt file.
#[test]
fn rejects_a_file_that_is_not_a_cookie_jar() {
    assert!(!has_netscape_header("LOGIN_INFO=AFmmF2s; SAPISID=abc"));
    assert!(!has_netscape_header(""));
    assert!(!has_netscape_header("{\"cookies\": []}"));
}

// ---------------------------------------------------------------------------
// Authentication status
// ---------------------------------------------------------------------------

#[test]
fn a_signed_in_jar_is_authenticated_and_reports_its_earliest_expiry() {
    let status = jar_status(&authenticated_jar(1_900_000_000));

    assert_eq!(status, JarStatus::Authenticated { expires: Some(1_900_000_000) });
    assert!(status.is_authenticated());
}

#[test]
fn a_logged_out_export_is_anonymous() {
    let status = jar_status(&anonymous_jar());

    assert_eq!(status, JarStatus::Anonymous);
    assert!(!status.is_authenticated());
}

/// yt-dlp needs *both* halves: `LOGIN_INFO` survives logout in some exports,
/// and a bare session ID without it does not authenticate either.
#[test]
fn either_half_alone_is_not_a_session() {
    let login_only =
        format!("{HEADER}.youtube.com\tTRUE\t/\tTRUE\t2000000000\tLOGIN_INFO\tv\n");
    let sid_only = format!(
        "{HEADER}#HttpOnly_.youtube.com\tTRUE\t/\tTRUE\t2000000000\tSAPISID\tv\n"
    );

    assert_eq!(jar_status(&login_only), JarStatus::Anonymous);
    assert_eq!(jar_status(&sid_only), JarStatus::Anonymous);
}

/// Cookies scoped to another host never reach `youtube.com` requests, so a jar
/// full of them is not a YouTube session however well-formed it looks.
#[test]
fn cookies_for_another_domain_do_not_authenticate() {
    let contents = format!(
        "{HEADER}.google.com\tTRUE\t/\tTRUE\t2000000000\tLOGIN_INFO\tv\n\
         .google.com\tTRUE\t/\tTRUE\t2000000000\tSAPISID\tv\n"
    );

    assert_eq!(jar_status(&contents), JarStatus::Anonymous);
}

#[test]
fn expires_in_counts_down_and_goes_negative_once_stale() {
    let status = JarStatus::Authenticated { expires: Some(1_000) };

    assert_eq!(status.expires_in(400), Some(600));
    assert_eq!(status.expires_in(1_500), Some(-500));
    assert_eq!(JarStatus::Anonymous.expires_in(400), None);
    assert_eq!(JarStatus::Authenticated { expires: None }.expires_in(400), None);
}

