/// The regression this list exists for. Once yt-dlp sees account cookies it
/// drops every requested client whose innertube profile is not
/// `SUPPORTS_COOKIES` — and since each attempt requests exactly one client, a
/// dropped client is an attempt that asks for nothing at all. Reusing the
/// anonymous list would waste half the fallback chain (`android_vr` and
/// `tv_simply`) on the very path the cookies were added to rescue.
#[test]
fn the_authenticated_clients_all_survive_yt_dlps_cookie_filter() {
    for client in AUTHED_STREAM_CLIENTS {
        assert!(
            !COOKIE_UNSUPPORTED_CLIENTS.contains(client),
            "yt-dlp discards `{client}` when cookies are supplied, so that \
             attempt would resolve nothing",
        );
    }
}

#[test]
fn the_anonymous_list_is_unchanged_when_no_jar_is_configured() {
    assert_eq!(stream_clients(false), STREAM_CLIENTS);
    assert_eq!(stream_clients(true), AUTHED_STREAM_CLIENTS);
}

#[test]
fn both_client_lists_are_non_empty_and_free_of_duplicates() {
    const EMPTY: &[&str] = &[];

    for list in [STREAM_CLIENTS, AUTHED_STREAM_CLIENTS] {
        assert_ne!(list, EMPTY, "a stream-client list is empty");

        let unique: HashSet<&&str> = list.iter().collect();
        assert_eq!(unique.len(), list.len(), "duplicate client in {list:?}");
    }
}

